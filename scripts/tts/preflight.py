#!/usr/bin/env python3
"""F7a pre-flight census for the parked audio re-synthesis (F7b, issue #178).

Read-only: recomputes, for every lesson x accent, what a fresh extraction
produces today vs what the shipped narration manifest contains — extracted
block count, tail sections present (Go deeper / Sources), and the recomputed
content hash vs the manifest's stored hash. It never synthesizes, never
decodes a .opus, and never writes outside --out (default: stdout).

The hash is synthesize.content_hash (single source): SHA-256 over the block
texts, each followed by "\\n". A mismatch means the shipped package is stale
relative to the current lesson prose — it says nothing about how the audio
sounds (manifest evidence is likely, not a listening pass).

Deficit split: blocks are segmented at the "Go deeper" and "Sources and
further reading" heading blocks (mid = before Go deeper, go = Go deeper up
to Sources, sources = Sources to the end) and the per-segment deficit is
extracted-minus-manifest per segment, so the three figures sum to the total.

Usage:
    python3 scripts/tts/preflight.py [--out docs/audio-preflight-report.md]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from extract_narration import LESSONS_DIR, extract_blocks
from synthesize import content_hash

ROOT = Path(__file__).resolve().parents[2]
AUDIO_DIR = ROOT / "public" / "audio"
ACCENTS = ("us", "uk")
GO_HEADING = "Go deeper"
SOURCES_HEADING = "Sources and further reading"

# Phase 1 expectation (pstack-interrogation-2026-11-12.md, section 1 F7,
# verified there). Compared against, never reconciled to: any deviation of
# the recomputed figures below is a FINDING (advisor condition, Branch 8).
EXPECTED = {"packages": 82, "mismatch": 82, "deficit": 529, "go": 254,
            "sources": 225, "mid": 50}


def segments(texts: list[str]) -> tuple[int, int, int]:
    """(mid, go, sources) block counts, split at the tail headings."""
    try:
        go = texts.index(GO_HEADING)
    except ValueError:
        return (len(texts), 0, 0)
    try:
        src = texts.index(SOURCES_HEADING)
    except ValueError:
        return (go, len(texts) - go, 0)
    return (go, src - go, len(texts) - src)


def census() -> tuple[list[dict], dict]:
    rows: list[dict] = []
    totals = {"packages": 0, "mismatch": 0, "self_mismatch": 0}
    per_accent = {a: {"deficit": 0, "go": 0, "sources": 0, "mid": 0}
                  for a in ACCENTS}
    for path in sorted(LESSONS_DIR.glob("*.mdx")):
        slug = path.stem
        extracted = [b["text"] for b in extract_blocks(path.read_text(encoding="utf-8"))]
        e_mid, e_go, e_src = segments(extracted)
        recomputed = content_hash(extracted)
        for accent in ACCENTS:
            manifest = json.loads(
                (AUDIO_DIR / slug / accent / "narration.json").read_text(encoding="utf-8")
            )
            shipped = [b["text"] for b in manifest["blocks"]]
            m_mid, m_go, m_src = segments(shipped)
            row = {
                "slug": slug,
                "accent": accent,
                "extracted": len(extracted),
                "shipped": len(shipped),
                "deficit": len(extracted) - len(shipped),
                "mid": e_mid - m_mid,
                "go": e_go - m_go,
                "sources": e_src - m_src,
                "go_extracted": GO_HEADING in extracted,
                "go_shipped": GO_HEADING in shipped,
                "sources_extracted": SOURCES_HEADING in extracted,
                "sources_shipped": SOURCES_HEADING in shipped,
                "hash_match": recomputed == manifest["contentHash"],
                "self_match": content_hash(shipped) == manifest["contentHash"],
            }
            rows.append(row)
            totals["packages"] += 1
            totals["mismatch"] += 0 if row["hash_match"] else 1
            totals["self_mismatch"] += 0 if row["self_match"] else 1
            acc = per_accent[accent]
            acc["deficit"] += row["deficit"]
            acc["go"] += row["go"]
            acc["sources"] += row["sources"]
            acc["mid"] += row["mid"]
    return rows, {"totals": totals, "per_accent": per_accent}


def render(rows: list[dict], summary: dict) -> str:
    totals, per_accent = summary["totals"], summary["per_accent"]
    us = per_accent["us"]
    lines = [
        "# Audio pre-flight report — F7a (generated, do not hand-edit)",
        "",
        "Generated by `python3 scripts/tts/preflight.py --out docs/audio-preflight-report.md`",
        "at HEAD of `feat/audio-resynthesis-preflight`. Read-only census: no synthesis",
        "was run, no `.opus` was decoded. Manifest evidence is **likely**, not a",
        "listening pass. This report does **not** claim F7 done; F7b (the synthesis",
        "itself, issue #178) is reserved to Liz's explicit word.",
        "",
        "## Headline (recomputed at run time)",
        "",
        f"- Packages checked: {totals['packages']} (41 lessons x US `af_heart` + UK `bf_emma`) — verified by this run.",
        f"- Recomputed hash vs manifest hash: **{totals['mismatch']}/{totals['packages']} mismatch**.",
        f"- Manifest self-consistency (hash of shipped block texts vs stored hash): {totals['self_mismatch']} mismatch — shipped manifests match their own (stale) block lists.",
        f"- Block deficit per accent (extracted today minus shipped): **{us['deficit']}** "
        f"(Go deeper {us['go']} + Sources {us['sources']} + mid-lesson drift {us['mid']}); "
        f"UK identical: {per_accent['uk']['deficit']} "
        f"({per_accent['uk']['go']} + {per_accent['uk']['sources']} + {per_accent['uk']['mid']}).",
        "- Packages whose shipped blocks contain a Go deeper heading: "
        f"{sum(r['go_shipped'] for r in rows)}/82; a Sources heading: "
        f"{sum(r['sources_shipped'] for r in rows)}/82. Extracted today: "
        f"{sum(r['go_extracted'] for r in rows)}/82 and {sum(r['sources_extracted'] for r in rows)}/82.",
        "",
        "## Expectation check (Phase 1 prediction vs recomputed)",
        "",
        "| Figure | Expected (Phase 1, verified there) | Recomputed (this run) | Match |",
        "|---|---|---|---|",
        f"| packages | {EXPECTED['packages']} | {totals['packages']} | {'yes' if totals['packages'] == EXPECTED['packages'] else 'NO — FINDING'} |",
        f"| hash mismatch | {EXPECTED['mismatch']}/82 | {totals['mismatch']}/82 | {'yes' if totals['mismatch'] == EXPECTED['mismatch'] else 'NO — FINDING'} |",
        f"| deficit / accent | {EXPECTED['deficit']} | {us['deficit']} (US), {per_accent['uk']['deficit']} (UK) | {'yes' if us['deficit'] == EXPECTED['deficit'] == per_accent['uk']['deficit'] else 'NO — FINDING'} |",
        f"| Go deeper / accent | {EXPECTED['go']} | {us['go']} (US), {per_accent['uk']['go']} (UK) | {'yes' if us['go'] == EXPECTED['go'] == per_accent['uk']['go'] else 'NO — FINDING'} |",
        f"| Sources / accent | {EXPECTED['sources']} | {us['sources']} (US), {per_accent['uk']['sources']} (UK) | {'yes' if us['sources'] == EXPECTED['sources'] == per_accent['uk']['sources'] else 'NO — FINDING'} |",
        f"| mid-lesson drift / accent | {EXPECTED['mid']} | {us['mid']} (US), {per_accent['uk']['mid']} (UK) | {'yes' if us['mid'] == EXPECTED['mid'] == per_accent['uk']['mid'] else 'NO — FINDING'} |",
        "",
        "Advisor condition (Branch 8): figures are recomputed, never reconciled to",
        "the expectation. A NO in the table above is a stop-and-report FINDING in",
        "the PR, not a number to fix up.",
        "",
        "## Per lesson x accent",
        "",
        "| Lesson | Accent | Extracted | Shipped | Deficit (mid/go/src) | Go deeper in shipped | Sources in shipped | Hash match |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['slug']} | {r['accent']} | {r['extracted']} | {r['shipped']} | "
            f"{r['deficit']} ({r['mid']}/{r['go']}/{r['sources']}) | "
            f"{'yes' if r['go_shipped'] else 'no'} | "
            f"{'yes' if r['sources_shipped'] else 'no'} | "
            f"{'yes' if r['hash_match'] else 'no'} |"
        )
    lines += [
        "",
        "Method: `extract_blocks()` from `scripts/tts/extract_narration.py` over",
        "`content/lessons/*.mdx`; hashes by `synthesize.content_hash` (SHA-256 over",
        "block texts, each followed by a newline). Segmentation at the `Go deeper`",
        "and `Sources and further reading` heading blocks.",
        "",
        "UNVERIFIED: the recorded audio itself — no `.opus` was decoded or listened",
        "to in Phase 1 or in this preflight (Phase 1 gap #5 in",
        "`pstack-interrogation-2026-11-12.md` section 5).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="F7a pre-flight census (read-only).")
    ap.add_argument("--out", default="", help="Write the report here (default: stdout)")
    args = ap.parse_args(argv)
    rows, summary = census()
    text = render(rows, summary)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"Wrote {args.out}: {summary['totals']['packages']} packages, "
              f"{summary['totals']['mismatch']} hash mismatches")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
